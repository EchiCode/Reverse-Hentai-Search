const source = readFileSync(new URL('../search.js', import.meta.url), 'utf8');
function client(fetch, hostname) {
    const context = vm.createContext({
        AbortController, DecompressionStream, Response, TextDecoder, TransformStream,
        URL, performance, setTimeout, clearTimeout, fetch,
        ...(hostname ? { location: { hostname } } : {}),
        console: { log() {}, debug() {}, warn() {} }
    });
    vm.runInContext(`${source}\nglobalThis.codecTests = {
        decodeCentroidsLVQ, rankCentroids, ensureCentroids, searchByClusters, createSearchDiagnostics, searchDataUrl
    };`, context);
    return context.codecTests;
}
const arrayBuffer = bytes => bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
const floatBytes = values => Buffer.from(values.buffer, values.byteOffset, values.byteLength).toString('hex');

test('localhost pages and workers use the colocated dataset while hosted pages keep production URLs', () => {
    for (const hostname of ['localhost', '127.0.0.1', '[::1]']) {
        const api = client(undefined, hostname);
        assert.equal(api.searchDataUrl('centroids'), 'data/centroids.lvq6.bin.gz');
        assert.equal(api.searchDataUrl('clusters', 7999), 'data/clusters/cluster_7999.bin.gz');
        assert.equal(api.searchDataUrl('meta', 62500), 'data/meta/meta_250.bin.gz');
    }
    const api = client(undefined, 'reverse-image-search.pages.dev');
    assert.equal(api.searchDataUrl('centroids'), 'centroids.lvq6.bin.gz');
    assert.equal(api.searchDataUrl('clusters', 7999),
        'https://batch-7.reverse-image-clusters-vers2.pages.dev/cluster_7999.bin.gz');
    assert.equal(api.searchDataUrl('meta', 62500),
        'https://batch-1.reverse-image-meta-vers2.pages.dev/meta_250.bin.gz');
});

