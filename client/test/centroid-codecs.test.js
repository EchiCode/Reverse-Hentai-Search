function packedIndex(bits, dimensions = 384, count = 2, version = 1) {
    const rowBytes = Math.ceil(dimensions * bits / 8);
    const lowerOffset = 16 + 2 * dimensions, deltaOffset = lowerOffset + 2 * count;
    const codesOffset = deltaOffset + 2 * count;
    const bytes = Buffer.alloc(codesOffset + count * rowBytes);
    bytes.write(`LVQ${bits}IDX\0`);
    bytes.writeUInt16LE(version, 8);
    bytes.writeUInt16LE(dimensions, 10);
    bytes.writeUInt32LE(count, 12);
    const expected = new Float32Array(count * dimensions);
    for (let row = 0; row < count; row++) {
        bytes.writeUInt16LE(0xbc00, lowerOffset + 2 * row); // -1
        bytes.writeUInt16LE(0x3400, deltaOffset + 2 * row); // .25
        for (let dimension = 0; dimension < dimensions; dimension++) {
            const code = (dimension * 31 + row * 17) % (1 << bits);
            expected[row * dimensions + dimension] = -1 + code * .25;
            for (let bit = 0; bit < bits; bit++) {
                if (code & (1 << bit)) {
                    const position = dimension * bits + bit;
                    bytes[codesOffset + row * rowBytes + (position >>> 3)] |= 1 << (position & 7);
                }
            }
        }
    }
    return { bytes, expected };
}

test('LVQ6 and LVQ8 reproduce benchmark Float32 bytes exactly', () => {
    const api = client();
    for (const fixture of golden) {
        const decoded = api.decodeCentroidsLVQ(arrayBuffer(Buffer.from(fixture.payload, 'base64')), 7);
        assert.equal(decoded.count, 4);
        assert.equal(decoded.vectorLength, 7);
        assert.equal(decoded.metric, 'ip');
        assert.equal(decoded.bias, null);
        assert.equal(floatBytes(decoded.vectors), fixture.float32hex, `LVQ${fixture.bits}`);
    }
});

test('six-bit boundaries and odd total payload lengths decode without crossing rows', () => {
    const api = client();
    for (const [bits, dimensions, count] of [[6, 384, 2], [6, 3, 3], [8, 3, 3], [6, 1, 3]]) {
        const { bytes, expected } = packedIndex(bits, dimensions, count);
        const decoded = api.decodeCentroidsLVQ(arrayBuffer(bytes), dimensions);
        assert.equal(floatBytes(decoded.vectors), floatBytes(expected));
    }
});

test('invalid headers, lengths, ranges and nonzero row padding are rejected', () => {
    const api = client(), original = Buffer.from(golden[0].payload, 'base64');
    const mutations = [
        bytes => bytes.write('LVQ5IDX\0'),
        bytes => bytes.writeUInt16LE(3, 8),
        bytes => bytes.writeUInt16LE(0, 10),
        bytes => bytes.writeUInt32LE(0, 12),
        bytes => bytes.writeUInt16LE(0x7c00, 30),
        bytes => bytes.writeUInt16LE(0, 38),
        bytes => bytes[51] |= 0x80,
    ];
    for (const mutate of mutations) {
        const bytes = Buffer.from(original);
        mutate(bytes);
        assert.throws(() => api.decodeCentroidsLVQ(arrayBuffer(bytes), 7), /LVQ/);
    }
    for (const bytes of [original.subarray(0, 15), original.subarray(0, -1), Buffer.concat([original, Buffer.alloc(1)])]) {
        assert.throws(() => api.decodeCentroidsLVQ(arrayBuffer(bytes), 7), /LVQ/);
    }
    assert.throws(() => api.decodeCentroidsLVQ(arrayBuffer(original)), /Unsupported/);
});

test('L2 centroids restore the mean before Float32 rounding and retain literal Float64 norms', () => {
    const api = client();
    for (const bits of [6, 8]) {
        const { bytes } = packedIndex(bits, 3, 3, 2);
        bytes.writeUInt16LE(0x3c00, 16); // mean[0] = 1
        bytes.writeUInt16LE(0x3800, 18); // mean[1] = .5
        bytes.writeUInt16LE(0xbc00, 20); // mean[2] = -1
        const decoded = api.decodeCentroidsLVQ(arrayBuffer(bytes), 3);
        const legacyBytes = Buffer.from(bytes);
        legacyBytes.writeUInt16LE(1, 8);
        const centered = api.decodeCentroidsLVQ(arrayBuffer(legacyBytes), 3);
        assert.equal(decoded.metric, 'l2');
        for (let row = 0; row < decoded.count; row++) {
            let squaredNorm = 0;
            for (let dimension = 0; dimension < 3; dimension++) {
                const offset = row * 3 + dimension;
                assert.equal(decoded.vectors[offset], Math.fround(centered.vectors[offset] + [1, .5, -1][dimension]));
                squaredNorm += decoded.vectors[offset] * decoded.vectors[offset];
            }
            assert.equal(decoded.bias[row], -.5 * squaredNorm);
        }
        bytes.writeUInt16LE(0x7c00, 16);
        assert.throws(() => api.decodeCentroidsLVQ(arrayBuffer(bytes), 3), /mean/);
    }
});

test('L2 routing uses centroid norm bias and preserves lower-ID ties', () => {
    const api = client();
    const index = { vectors: new Float32Array([10, 0, 1, 0, 1, 0]), count: 3, vectorLength: 2,
        metric: 'l2', bias: new Float64Array([-50, -.5, -.5]) };
    const l2 = api.rankCentroids([.9, 0], index, 3);
    assert.deepEqual(Array.from(l2, point => point.id), [1, 2, 0]);
    assert.deepEqual(Array.from(api.rankCentroids([.9, 0], { ...index, metric: 'ip', bias: null }, 3), point => point.id), [0, 1, 2]);
    const tiny = 2 ** -13;
    const close = { vectors: new Float32Array([1, tiny, 1, 0]), count: 2, vectorLength: 2,
        metric: 'l2', bias: new Float64Array([-.5 * (1 + tiny * tiny), -.5]) };
    assert.equal(api.rankCentroids([1, 0], close, 1)[0].id, 1);
});

test('L2 mean restoration happens before Float32 rounding', () => {
    const api = client();
    for (const bits of [6, 8]) {
        const { bytes } = packedIndex(bits, 1, 2, 2);
        bytes.writeUInt16LE(0xfbff, 16); // mean = -65504
        for (let row = 0; row < 2; row++) {
            bytes.writeUInt16LE(0x7bff, 18 + row * 2); // lower = 65504
            bytes.writeUInt16LE(0x0400, 22 + row * 2); // delta = 2^-14
        }
        bytes[26] = 1;
        bytes[27] = 0;
        const decoded = api.decodeCentroidsLVQ(arrayBuffer(bytes), 1);
        assert.equal(decoded.vectors[0], 2 ** -14);
        assert.equal(decoded.vectors[1], 0);
        assert.equal(api.rankCentroids([2 ** -14], decoded, 1)[0].id, 0);
    }
});

test('L2 routing retains head IDs above uint16 range', () => {
    const api = client(), count = 70000;
    const { bytes } = packedIndex(6, 1, count, 2);
    const codesOffset = 16 + 2 + 4 * count;
    bytes.fill(0, codesOffset);
    bytes[codesOffset + count - 1] = 8; // Last centroid is +1; every earlier centroid is -1.
    const decoded = api.decodeCentroidsLVQ(arrayBuffer(bytes), 1);
    assert.equal(api.rankCentroids([1], decoded, 1)[0].id, count - 1);
});

test('search fetches the L2-nearest posting while legacy IP keeps its existing route', async () => {
    for (const version of [1, 2]) {
        const { bytes } = packedIndex(6, 384, 2, version);
        const lowerOffset = 16 + 2 * 384, codesOffset = lowerOffset + 8;
        bytes.writeUInt16LE(0, lowerOffset);
        bytes.writeUInt16LE(0, lowerOffset + 2);
        bytes.fill(0, codesOffset);
        bytes[codesOffset] = 40; // centroid 0 = [10, 0, ...]
        bytes[codesOffset + 288] = 4; // centroid 1 = [1, 0, ...]
        const requests = [];
        const api = client(async url => {
            requests.push(url);
            return new Response(gzipSync(url === 'centroids.lvq6.bin.gz' ? bytes : Buffer.alloc(0)));
        });
        const query = new Float32Array(384);
        query[0] = .9;
        const result = await api.searchByClusters(query, {
            signal: new AbortController().signal, threshold: 0, clusters: 1
        });
        assert.equal(result.totalCompared, 0);
        const expectedId = version === 2 ? 1 : 0;
        assert.deepEqual(requests, ['centroids.lvq6.bin.gz',
            `https://batch-0.reverse-image-clusters-vers2.pages.dev/cluster_${expectedId}.bin.gz`]);
    }
});

test('loading uses LVQ6 and retains the shared decoded index in the page cache', async () => {
    const requests = [], compressed = gzipSync(packedIndex(6).bytes);
    const api = client(async url => {
        requests.push(url);
        return new Response(compressed);
    });
    const first = await api.ensureCentroids(undefined, api.createSearchDiagnostics());
    const diagnostics = api.createSearchDiagnostics();
    const second = await api.ensureCentroids(undefined, diagnostics);
    assert.equal(first, second);
    assert.deepEqual(requests, ['centroids.lvq6.bin.gz']);
    assert.equal(diagnostics.resources.length, 1);
    assert.equal(diagnostics.resources[0].cacheHit, true);
    assert.equal(diagnostics.resources[0].url, 'centroids.lvq6.bin.gz');
});

test('cancelling one consumer preserves a shared LVQ6 preload', async () => {
    let release;
    const pending = new Promise(resolve => { release = resolve; });
    const api = client(() => pending), controller = new AbortController();
    const cancelled = api.ensureCentroids(controller.signal);
    const shared = api.ensureCentroids();
    controller.abort(new Error('cancel this search'));
    await assert.rejects(cancelled, /cancel this search/);
    release(new Response(gzipSync(packedIndex(6).bytes)));
    assert.equal((await shared).count, 2);
    assert.equal(await api.ensureCentroids(), await shared);
});
